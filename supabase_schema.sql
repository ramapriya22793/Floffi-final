-- 1. Create 'products' table
CREATE TABLE IF NOT EXISTS public.products (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL, -- 'jam', 'nectar-spread', 'thokku'
    image TEXT NOT NULL,
    price NUMERIC NOT NULL,
    original_price NUMERIC,
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable RLS & allow public reads on products
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read on products" 
ON public.products 
FOR SELECT 
USING (true);

CREATE POLICY "Allow all operations for service role/admin on products" 
ON public.products 
FOR ALL 
USING (true);

